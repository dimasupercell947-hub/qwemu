import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(join(root, path), 'utf8');
const required = ['public/index.html','public/assets/main.js','public/assets/library-store.js','src-tauri/Cargo.toml','src-tauri/build.rs','src-tauri/src/lib.rs','src-tauri/src/main.rs','src-tauri/tauri.conf.json','src-tauri/capabilities/default.json','src-tauri/icons/icon.ico','run.bat','build.bat','check.bat'];
for (const path of required) assert.ok(existsSync(join(root,path)), 'Missing required file: ' + path);
const config = JSON.parse(read('src-tauri/tauri.conf.json'));
assert.equal(config.productName,'QWEMU MUSIC');
assert.equal(config.version,'1.5.0');
assert.equal(config.identifier,'com.qwemu.music.desktop');
assert.equal(config.build.frontendDist,'../public');
assert.deepEqual(config.bundle.targets,['nsis','msi']);
assert.ok(config.app.windows.some(win => win.label==='main' && win.minWidth>=960));
assert.match(read('public/index.html'),/QWEMU_DESKTOP = true/);
const main = read('public/assets/main.js');
assert.ok(main.includes('new LibraryStore'));
assert.ok(main.includes('restoreDesktopLibrary'));
assert.ok(main.includes('libraryStore.getFile'));
assert.ok(main.includes('libraryStore.put'));
const store = read('public/assets/library-store.js');
assert.ok(store.includes('indexedDB.open'));
assert.ok(store.includes('async getFile'));
assert.match(read('src-tauri/Cargo.toml'),/tauri = \{ version = "2" \}/);
assert.match(read('src-tauri/src/main.rs'),/qwemu_music_desktop_lib::run/);
console.log('QWEMU Desktop smoke test passed: ' + required.length + ' required files and desktop persistence checks.');
